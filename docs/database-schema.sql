-- Airsell Cargo portal: proposed initial PostgreSQL schema.
-- Planning artifact only; review and apply through a migration tool in development first.
-- Requires PostgreSQL 14+. This schema stores private document metadata, not file bytes.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TYPE account_kind AS ENUM ('customer', 'staff');
CREATE TYPE membership_role AS ENUM ('customer_admin', 'customer_member');
CREATE TYPE staff_role AS ENUM ('sales', 'operations', 'documentation', 'finance', 'admin');
CREATE TYPE enquiry_status AS ENUM ('new', 'reviewing', 'quoted', 'accepted', 'declined', 'converted', 'closed');
CREATE TYPE quote_status AS ENUM ('draft', 'sent', 'accepted', 'declined', 'expired', 'cancelled');
CREATE TYPE shipment_direction AS ENUM ('export', 'import', 'other');
CREATE TYPE shipment_status AS ENUM ('booked', 'pickup_scheduled', 'received_at_hga', 'documents_review', 'customs_processing', 'ready_for_dispatch', 'departed', 'arrived', 'delivery_in_progress', 'delivered', 'on_hold', 'delayed', 'cancelled', 'completed');
CREATE TYPE document_status AS ENUM ('uploaded', 'under_review', 'approved', 'rejected');
CREATE TYPE invoice_status AS ENUM ('draft', 'issued', 'partially_paid', 'paid', 'void', 'overdue');
CREATE TYPE audit_event_type AS ENUM ('enquiry_created', 'enquiry_updated', 'quote_created', 'quote_sent', 'quote_accepted', 'quote_declined', 'shipment_created', 'shipment_status_changed', 'document_uploaded', 'document_reviewed', 'invoice_updated', 'user_access_changed');

CREATE TABLE organizations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    legal_name text NOT NULL CHECK (length(trim(legal_name)) BETWEEN 1 AND 200),
    display_name text CHECK (display_name IS NULL OR length(trim(display_name)) <= 200),
    country_code char(2),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email text NOT NULL,
    full_name text NOT NULL CHECK (length(trim(full_name)) BETWEEN 1 AND 200),
    phone text,
    account_kind account_kind NOT NULL,
    -- Hash generated by a maintained password-hashing implementation (e.g. Argon2id), never plaintext.
    password_hash text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_format CHECK (email = lower(trim(email)) AND position('@' IN email) > 1),
    CONSTRAINT users_password_hash_not_empty CHECK (password_hash IS NULL OR length(password_hash) > 20)
);

CREATE TABLE organization_memberships (
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role membership_role NOT NULL DEFAULT 'customer_member',
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, user_id)
);

CREATE TABLE user_staff_roles (
    user_id uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    role staff_role NOT NULL,
    granted_by uuid REFERENCES users(id) ON DELETE RESTRICT,
    granted_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role)
);

CREATE TABLE enquiries (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    public_reference text NOT NULL UNIQUE,
    organization_id uuid REFERENCES organizations(id) ON DELETE RESTRICT,
    contact_name text NOT NULL CHECK (length(trim(contact_name)) BETWEEN 1 AND 200),
    company_name text,
    email text NOT NULL,
    phone text NOT NULL,
    direction shipment_direction NOT NULL,
    requested_service text NOT NULL CHECK (length(trim(requested_service)) BETWEEN 1 AND 120),
    origin text NOT NULL CHECK (length(trim(origin)) BETWEEN 1 AND 200),
    destination text NOT NULL CHECK (length(trim(destination)) BETWEEN 1 AND 200),
    cargo_description text NOT NULL CHECK (length(trim(cargo_description)) BETWEEN 1 AND 2000),
    weight_kg numeric(12, 3) CHECK (weight_kg IS NULL OR weight_kg > 0),
    notes text CHECK (notes IS NULL OR length(notes) <= 5000),
    status enquiry_status NOT NULL DEFAULT 'new',
    assigned_to uuid REFERENCES users(id) ON DELETE RESTRICT,
    consent_recorded_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT enquiry_email_format CHECK (position('@' IN email) > 1)
);

CREATE TABLE quotes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    enquiry_id uuid NOT NULL REFERENCES enquiries(id) ON DELETE RESTRICT,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    status quote_status NOT NULL DEFAULT 'draft',
    currency char(3) NOT NULL,
    total_amount numeric(14, 2) NOT NULL CHECK (total_amount >= 0),
    inclusions text,
    exclusions text,
    terms text,
    valid_until timestamptz,
    created_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    sent_at timestamptz,
    accepted_at timestamptz,
    declined_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT quote_version_unique UNIQUE (enquiry_id, version),
    CONSTRAINT quote_currency_format CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT quote_sent_has_timestamp CHECK (status NOT IN ('sent', 'accepted', 'declined', 'expired') OR sent_at IS NOT NULL)
);

CREATE TABLE shipments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    public_reference text NOT NULL UNIQUE,
    organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
    enquiry_id uuid NOT NULL UNIQUE REFERENCES enquiries(id) ON DELETE RESTRICT,
    accepted_quote_id uuid NOT NULL UNIQUE REFERENCES quotes(id) ON DELETE RESTRICT,
    direction shipment_direction NOT NULL,
    origin text NOT NULL,
    destination text NOT NULL,
    cargo_description text NOT NULL,
    piece_count integer CHECK (piece_count IS NULL OR piece_count > 0),
    weight_kg numeric(12, 3) CHECK (weight_kg IS NULL OR weight_kg > 0),
    volume_cbm numeric(12, 4) CHECK (volume_cbm IS NULL OR volume_cbm > 0),
    status shipment_status NOT NULL DEFAULT 'booked',
    assigned_to uuid REFERENCES users(id) ON DELETE RESTRICT,
    estimated_departure date,
    estimated_arrival date,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT shipment_date_order CHECK (estimated_departure IS NULL OR estimated_arrival IS NULL OR estimated_arrival >= estimated_departure)
);

CREATE TABLE shipment_events (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shipment_id uuid NOT NULL REFERENCES shipments(id) ON DELETE RESTRICT,
    status shipment_status NOT NULL,
    customer_message text,
    internal_note text,
    is_customer_visible boolean NOT NULL DEFAULT true,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid REFERENCES users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE documents (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shipment_id uuid NOT NULL REFERENCES shipments(id) ON DELETE RESTRICT,
    document_type text NOT NULL CHECK (length(trim(document_type)) BETWEEN 1 AND 100),
    storage_key text NOT NULL UNIQUE,
    original_filename text NOT NULL CHECK (length(trim(original_filename)) BETWEEN 1 AND 255),
    content_type text NOT NULL CHECK (length(trim(content_type)) <= 150),
    size_bytes bigint NOT NULL CHECK (size_bytes > 0),
    status document_status NOT NULL DEFAULT 'uploaded',
    uploaded_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reviewed_by uuid REFERENCES users(id) ON DELETE RESTRICT,
    review_note text,
    uploaded_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    CONSTRAINT document_review_consistent CHECK ((reviewed_at IS NULL AND reviewed_by IS NULL) OR (reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL))
);

CREATE TABLE invoices (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    public_reference text NOT NULL UNIQUE,
    shipment_id uuid NOT NULL REFERENCES shipments(id) ON DELETE RESTRICT,
    currency char(3) NOT NULL,
    total_amount numeric(14, 2) NOT NULL CHECK (total_amount >= 0),
    status invoice_status NOT NULL DEFAULT 'draft',
    issued_at timestamptz,
    due_at timestamptz,
    created_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT invoice_currency_format CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT invoice_due_after_issue CHECK (issued_at IS NULL OR due_at IS NULL OR due_at >= issued_at)
);

CREATE TABLE payments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    invoice_id uuid NOT NULL REFERENCES invoices(id) ON DELETE RESTRICT,
    amount numeric(14, 2) NOT NULL CHECK (amount > 0),
    currency char(3) NOT NULL,
    payment_reference text,
    payment_method text,
    received_at timestamptz NOT NULL,
    recorded_by uuid NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT payment_currency_format CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE audit_events (
    id bigserial PRIMARY KEY,
    event_type audit_event_type NOT NULL,
    actor_user_id uuid REFERENCES users(id) ON DELETE RESTRICT,
    enquiry_id uuid REFERENCES enquiries(id) ON DELETE RESTRICT,
    quote_id uuid REFERENCES quotes(id) ON DELETE RESTRICT,
    shipment_id uuid REFERENCES shipments(id) ON DELETE RESTRICT,
    document_id uuid REFERENCES documents(id) ON DELETE RESTRICT,
    invoice_id uuid REFERENCES invoices(id) ON DELETE RESTRICT,
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX enquiries_status_created_idx ON enquiries (status, created_at DESC);
CREATE INDEX enquiries_assignee_status_idx ON enquiries (assigned_to, status) WHERE assigned_to IS NOT NULL;
CREATE INDEX quotes_enquiry_status_idx ON quotes (enquiry_id, status, created_at DESC);
CREATE INDEX shipments_org_status_idx ON shipments (organization_id, status, created_at DESC);
CREATE INDEX shipments_assignee_status_idx ON shipments (assigned_to, status) WHERE assigned_to IS NOT NULL;
CREATE INDEX shipment_events_timeline_idx ON shipment_events (shipment_id, occurred_at DESC);
CREATE INDEX documents_shipment_status_idx ON documents (shipment_id, status, uploaded_at DESC);
CREATE INDEX invoices_shipment_status_idx ON invoices (shipment_id, status);
CREATE INDEX payments_invoice_received_idx ON payments (invoice_id, received_at DESC);
CREATE INDEX audit_events_shipment_created_idx ON audit_events (shipment_id, created_at DESC) WHERE shipment_id IS NOT NULL;
CREATE INDEX audit_events_enquiry_created_idx ON audit_events (enquiry_id, created_at DESC) WHERE enquiry_id IS NOT NULL;

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER organizations_set_updated_at BEFORE UPDATE ON organizations FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER enquiries_set_updated_at BEFORE UPDATE ON enquiries FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER quotes_set_updated_at BEFORE UPDATE ON quotes FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER shipments_set_updated_at BEFORE UPDATE ON shipments FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER invoices_set_updated_at BEFORE UPDATE ON invoices FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMIT;
