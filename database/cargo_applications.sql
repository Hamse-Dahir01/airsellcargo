CREATE TABLE IF NOT EXISTS cargo_applications (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reference VARCHAR(30) NOT NULL,
    hawb_number VARCHAR(100) NULL,
    sender_name VARCHAR(50) NOT NULL,
    sender_phone VARCHAR(11) NOT NULL,
    sender_address VARCHAR(100) NOT NULL,
    receiver_name VARCHAR(50) NOT NULL,
    receiver_phone VARCHAR(11) NOT NULL,
    receiver_address VARCHAR(100) NOT NULL,
    origin VARCHAR(50) NOT NULL,
    destination VARCHAR(50) NOT NULL,
    shipment_date DATE NOT NULL,
    pieces INT UNSIGNED NOT NULL,
    weight_kg DECIMAL(10,2) NOT NULL,
    dimensions VARCHAR(100) NULL,
    cargo_description VARCHAR(1000) NOT NULL,
    payment_terms VARCHAR(50) NOT NULL,
    special_instructions VARCHAR(1000) NULL,
    consent_given TINYINT(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cargo_applications_reference (reference),
    UNIQUE KEY uq_cargo_applications_hawb (hawb_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
